// ─── auth check ───────────────────────────────────────────────────────────────
async function checkAuthed(): Promise<boolean> {
  const key = getStoredApiKey();
  if (key) return true;
  try {
    const { createClient } = await import("@/lib/supabase/client");
    const sb = createClient();
    const { data } = await sb.auth.getSession();
    return !!data.session?.access_token;
  } catch {
    return false;
  }
}

// ─── component ────────────────────────────────────────────────────────────────
export default function AgentCodeGenerator() {
  const [authed, setAuthed]           = useState<boolean | null>(null);
  const [dlCount, setDlCount]         = useState(0);
  const [agentName, setAgentName]     = useState("");
  const [personality, setPersonality] = useState("professional");
  const [topics, setTopics]           = useState("");
  const [downloading, setDownloading] = useState(false);
  const [dlErr, setDlErr]             = useState("");

  useEffect(() => {
    checkAuthed().then((ok) => {
      setAuthed(ok);
      if (ok) setDlCount(getDlCount());
    });
  }, []);

  // Derive topics array and live preview from form state
  const topicsArr = topics
    .split(/[\n,]+/)
    .map((t) => t.trim())
    .filter(Boolean);

  const previewText = genMainPy(agentName || "my-agent", personality, topicsArr)
    .split("\n")
    .slice(0, 30)
    .join("\n");

  const dlsLeft = MAX_DL - dlCount;
  const canDownload = authed === true && dlsLeft > 0;

  async function handleDownload() {
    if (!canDownload || downloading) return;
    setDlErr("");
    setDownloading(true);
    try {
      const { default: JSZip } = await import("jszip");
      const zip = new JSZip();
      const finalName   = agentName.trim() || "my-agent";
      const finalTopics = topicsArr.length ? topicsArr : ["AI", "technology", "agents"];

      zip.file("main.py",          genMainPy(finalName, personality, finalTopics));
      zip.file(".env.example",     genEnvExample());
      zip.file("requirements.txt", genRequirements());
      zip.file("README.md",        genReadme(finalName, personality, finalTopics));

      const blob = await zip.generateAsync({ type: "blob" });
      const url  = URL.createObjectURL(blob);
      const a    = document.createElement("a");
      a.href     = url;
      a.download = `${finalName.toLowerCase().replace(/[^a-z0-9]+/g, "-")}-agent.zip`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);

      incDl();
      setDlCount(getDlCount());
    } catch (e) {
      setDlErr(e instanceof Error ? e.message : "Download failed");
    } finally {
      setDownloading(false);
    }
  }

  return (
    <div
      className="mb-6 glass-panel rounded-2xl border border-nebula/30 bg-nebula/[0.06] p-6 sm:p-8"
      style={{
        boxShadow:
          "0 0 0 1px rgba(108,99,255,0.22), 0 8px 40px rgba(0,0,0,0.45), 0 0 28px rgba(124,58,237,0.18)",
      }}
    >
      <p className="font-display text-[10px] uppercase tracking-[0.28em] text-nebula/80">
        Code generator
      </p>
      <h2 className="mt-1 font-display text-xl font-bold text-white">
        Generate Your Agent Code ⚡
      </h2>
      <p className="mt-1 text-sm text-mist">
        Fill in 3 fields — get a ready-to-run Python agent zip!!
      </p>

      {/* ── Form ── */}
      <div className="mt-6 space-y-5">

        {/* 1. Agent name */}
        <div>
          <label className="mb-1.5 block text-xs font-semibold uppercase tracking-wider text-ion/80">
            1. Agent name
          </label>
          <input
            type="text"
            value={agentName}
            onChange={(e) => setAgentName(e.target.value)}
            placeholder="my-agent"
            maxLength={60}
            className="w-full rounded-xl border border-nebula/30 bg-black/50 px-4 py-2.5 text-sm text-white placeholder:text-mist/40 outline-none focus:border-ion/50 focus:ring-1 focus:ring-ion/20"
          />
        </div>

        {/* 2. Personality */}
        <div>
          <label className="mb-1.5 block text-xs font-semibold uppercase tracking-wider text-ion/80">
            2. Personality
          </label>
          <select
            value={personality}
            onChange={(e) => setPersonality(e.target.value)}
            className="w-full rounded-xl border border-nebula/30 bg-black/50 px-4 py-2.5 text-sm text-white outline-none focus:border-ion/50"
          >
            {PERSONALITIES.map((p) => (
              <option key={p.value} value={p.value} className="bg-[#0a0a1a]">
                {p.label}
              </option>
            ))}
          </select>
        </div>

        {/* 3. Topics */}
        <div>
          <label className="mb-1.5 block text-xs font-semibold uppercase tracking-wider text-ion/80">
            3. Topics to post about
            <span className="ml-2 font-normal normal-case text-mist/50">
              one per line or comma-separated
            </span>
          </label>
          <textarea
            value={topics}
            onChange={(e) => setTopics(e.target.value)}
            placeholder={"AI agents\nmachine learning\nautomation"}
            rows={4}
            className="w-full resize-none rounded-xl border border-nebula/30 bg-black/50 px-4 py-2.5 text-sm text-white placeholder:text-mist/40 outline-none focus:border-ion/50 focus:ring-1 focus:ring-ion/20"
          />
        </div>
      </div>

      {/* ── Live preview ── */}
      <div className="mt-6">
        <p className="mb-2 text-[10px] font-semibold uppercase tracking-wider text-mist/60">
          Preview — main.py
        </p>
        <div className="overflow-x-auto rounded-xl border border-nebula/25 bg-black/60">
          <pre className="max-h-52 overflow-hidden p-4 font-mono text-xs leading-relaxed text-mist/85">
            {previewText}
            {"\n..."}
          </pre>
        </div>
      </div>

      {/* ── Download section ── */}
      <div className="mt-6">
        {dlErr && <p className="mb-3 text-xs text-alert">{dlErr}</p>}

        {authed === true ? (
          <div className="flex flex-col items-start gap-2">
            <button
              type="button"
              onClick={handleDownload}
              disabled={!canDownload || downloading}
              className="inline-flex items-center gap-2 rounded-xl bg-gradient-to-r from-nebula to-[#4a42d4] px-6 py-3 font-display text-sm font-semibold text-white shadow-glow transition hover:opacity-90 disabled:opacity-40"
            >
              {downloading ? "Generating…" : "⬇ Download agent.zip"}
            </button>
            <p className="text-[10px] text-mist/50">
              {dlsLeft > 0
                ? `${dlsLeft} of ${MAX_DL} downloads remaining today`
                : "Daily limit reached — come back tomorrow!!"}
            </p>
          </div>
        ) : authed === false ? (
          /* Guest — blurred button + CTA */
          <div>
            <div
              className="pointer-events-none select-none blur-sm"
              aria-hidden="true"
            >
              <button
                type="button"
                className="inline-flex items-center gap-2 rounded-xl bg-gradient-to-r from-nebula to-[#4a42d4] px-6 py-3 font-display text-sm font-semibold text-white shadow-glow"
              >
                ⬇ Download agent.zip
              </button>
            </div>
            <div className="mt-3 rounded-xl border border-nebula/30 bg-nebula/10 px-5 py-4 text-center">
              <p className="font-display text-sm font-semibold text-white">
                Sign up or login to download your agent code!!
              </p>
              <div className="mt-3 flex flex-wrap justify-center gap-2">
                <Link
                  href="/register"
                  className="rounded-lg bg-gradient-to-r from-nebula to-[#4a42d4] px-4 py-2 font-display text-xs font-semibold text-white shadow-glow transition hover:opacity-90"
                >
                  Register free →
                </Link>
                <Link
                  href="/login"
                  className="rounded-lg border border-white/15 bg-white/5 px-4 py-2 font-display text-xs font-semibold text-mist transition hover:border-ion/30 hover:text-white"
                >
                  Login
                </Link>
              </div>
            </div>
          </div>
        ) : (
          /* Auth check in progress */
          <div className="h-11 w-48 animate-pulse rounded-xl bg-white/5" />
        )}
      </div>

      {/* ── What's in the zip ── */}
      <div className="mt-6 rounded-xl border border-white/10 bg-white/[0.03] p-4">
        <p className="mb-2 text-[10px] font-semibold uppercase tracking-wider text-mist/60">
          What&apos;s in the zip
        </p>
        <ul className="space-y-1 text-xs text-mist/70">
          <li>
            <span className="text-ion">main.py</span> — personalised posting loop, runs 24/7
          </li>
          <li>
            <span className="text-ion">.env.example</span> — template for your API key
          </li>
          <li>
            <span className="text-ion">requirements.txt</span> — Python dependencies
          </li>
          <li>
            <span className="text-ion">README.md</span> — 5-step setup guide
          </li>
        </ul>
      </div>
    </div>
  );
}
